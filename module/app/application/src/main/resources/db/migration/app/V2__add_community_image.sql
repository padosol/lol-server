-- lol-db-schema V36 을 app 체인으로 옮긴 것.
--
-- 운영 DB 는 V35 상태라 baseline(V1) 뒤 이 파일이 처음 실행된다. lol-repository 가 공유 체인으로
-- V36 을 먼저 적용했더라도(public 에 생성 → 02-move-schema.sql 로 app 이동) 실패하지 않도록
-- 생성문은 IF NOT EXISTS 로 둔다.
--
-- 커뮤니티 게시글 본문 이미지
--
-- post_id 가 NULL 을 허용하는 이유: 업로드는 글 저장보다 먼저 일어난다(에디터에서
-- 이미지를 넣은 뒤 글을 쓰다 만 상태). 이 구간의 행이 status=PENDING 이고,
-- 유예기간이 지나면 정리 배치가 스토리지와 함께 지운다.
--
-- 행은 S3 PUT '전에' 먼저 INSERT 된다(status=UPLOADING). 그래야 DB 가 항상 S3 의
-- 상위집합이 되어, 버킷에만 존재하고 DB 가 모르는 파일이 생기지 않는다.
-- 반대 순서(PUT 먼저)로 하면 PUT 성공 후 INSERT 가 실패한 파일은 DB 에 흔적이 없어
-- 정리 배치가 영영 찾지 못한 채 버킷에만 쌓인다.
CREATE TABLE IF NOT EXISTS community_image (
    id           BIGINT        NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    member_id    BIGINT        NOT NULL,
    post_id      BIGINT        NULL,
    -- 스토리지 내 불변 키. URL 은 CDN 도메인 변경에 따라 바뀔 수 있으므로
    -- 참조의 진실원천은 이 컬럼이다.
    storage_key  VARCHAR(512)  NOT NULL,
    -- 발급 당시 URL 스냅샷(감사/디버깅용). 조회 응답은 storage_key + base-url 로 조합한다.
    url          VARCHAR(1024) NOT NULL,
    content_type VARCHAR(50)   NOT NULL,
    size_bytes   BIGINT        NOT NULL,
    width        INT           NULL,
    height       INT           NULL,
    -- UPLOADING / PENDING / ATTACHED / DETACHED. duo_post.status 와 같이 문자열로
    -- 저장하고 도메인 enum 매핑은 애플리케이션이 담당한다(값 추가 시 마이그레이션 불필요).
    status       VARCHAR(20)   NOT NULL,
    created_at   TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_community_image PRIMARY KEY (id),
    CONSTRAINT fk_ci_member FOREIGN KEY (member_id) REFERENCES member (id),
    -- ON DELETE 없음: 게시글은 soft delete 이므로 물리 삭제가 발생하지 않는다.
    CONSTRAINT fk_ci_post FOREIGN KEY (post_id) REFERENCES community_post (id),
    -- 같은 키로 두 행이 생기면 정리 배치가 남의 파일을 지운다.
    CONSTRAINT uq_ci_storage_key UNIQUE (storage_key)
);

-- 게시글 상세/수정 시 첨부 목록 조회.
-- PENDING 구간의 행(post_id IS NULL)이 대부분을 차지할 수 있어 부분 인덱스로 둔다.
CREATE INDEX IF NOT EXISTS idx_ci_post ON community_image (post_id) WHERE post_id IS NOT NULL;

-- 정리 배치: status + 경과시간으로 스캔한다. created_at 이 아니라 updated_at 인 이유는
-- DETACHED 유예를 "떨어져 나온 시점"부터 세야 하기 때문이다. 1년 전에 올린 이미지를
-- 오늘 글에서 뺐는데 created_at 으로 재면 즉시 삭제 대상이 된다.
-- UPLOADING·PENDING 은 두 값이 같으므로 이 인덱스 하나로 세 조회가 모두 커버된다.
CREATE INDEX IF NOT EXISTS idx_ci_status_updated ON community_image (status, updated_at);

-- 회원별 업로드 조회(남용 추적·마이페이지 확장 대비).
CREATE INDEX IF NOT EXISTS idx_ci_member_created ON community_image (member_id, created_at DESC);

COMMENT ON TABLE community_image IS '커뮤니티 게시글 본문 이미지';
COMMENT ON COLUMN community_image.storage_key IS '오브젝트 스토리지 내 불변 키 ({env}/community/{yyyy}/{MM}/{uuid}.{ext})';
COMMENT ON COLUMN community_image.url IS '발급 당시 CDN URL 스냅샷. 조회 응답은 storage_key + base-url 로 조합한다';
COMMENT ON COLUMN community_image.status IS 'UPLOADING(행만 존재) / PENDING(업로드 완료, 글 미첨부) / ATTACHED(글에 첨부) / DETACHED(글에서 분리, 유예 후 삭제)';
