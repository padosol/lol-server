-- lol-server app 스키마 초기 상태 (member · community · duo)
--
-- lol-db-schema V1~V35 를 빈 DB 에 적용한 뒤 app 테이블 13개만 pg_dump 해 만들었다.
-- 운영 DB 는 이 상태의 테이블을 public 에서 app 으로 옮긴 뒤(docs/db-split/02-move-schema.sql)
-- baseline-on-migrate 로 이 버전을 baseline 처리하므로 운영에서는 실행되지 않는다.
-- 빈 DB(local·테스트)에서만 실행된다. 수정 금지 — 변경은 새 버전으로 추가한다.
--
-- 객체는 스키마를 붙이지 않는다. Flyway 가 search_path 를 default-schema(app)로 두고 실행한다.

CREATE TABLE community_board_group (
    id bigint NOT NULL,
    code character varying(50) NOT NULL,
    display_order integer DEFAULT 0 NOT NULL,
    active boolean DEFAULT true NOT NULL,
    created_at timestamp without time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at timestamp without time zone DEFAULT CURRENT_TIMESTAMP NOT NULL
);

COMMENT ON TABLE community_board_group IS '커뮤니티 사이드바 게시판 그룹(섹션)';

COMMENT ON COLUMN community_board_group.code IS '그룹 식별 코드 (COMMUNITY/ESPORTS/INFO)';

COMMENT ON COLUMN community_board_group.display_order IS '사이드바 그룹 노출 순서(전역, 오름차순). 10 단위로 부여';

CREATE TABLE community_board_group_i18n (
    group_id bigint NOT NULL,
    locale character varying(10) NOT NULL,
